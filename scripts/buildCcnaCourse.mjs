import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const sourcePath = path.join(root, 'docs/CCNA_NETWORKING_KNOWLEDGE_BASE.md')
const outputPath = path.join(root, 'src/content/ccnaCourse.generated.ts')
const source = fs.readFileSync(sourcePath, 'utf8')
const lines = source.split(/\r?\n/)

const chapterPattern = /^#\s+(\d+)\.\s+Chapter\s+(\d+):\s+(.+)$/
const appendixPattern = /^#\s+(\d+)\.\s+(.+)$/
const sectionPattern = /^##\s+(\d+\.\d+)\s+(.+)$/
const appendixSectionPattern = /^###\s+(.+)$/

const chapters = []
let chapter = null
let section = null
let appendixSectionCount = 0
let appendixBookNumber = '5'

const cleanContent = (value) => value
  .replace(/^\s*---\s*$/gm, '')
  .replace(/\n{3,}/g, '\n\n')
  .trim()

const finishSection = () => {
  if (!chapter || !section) return
  section.markdown = cleanContent(section.lines.join('\n'))
  delete section.lines
  if (section.markdown) chapter.sections.push(section)
  section = null
}

const finishChapter = () => {
  finishSection()
  if (chapter && chapter.sections.length) chapters.push(chapter)
  chapter = null
}

for (const line of lines) {
  const chapterMatch = line.match(chapterPattern)
  if (chapterMatch) {
    finishChapter()
    chapter = {
      id: `ch${chapterMatch[2]}`,
      bookNumber: chapterMatch[2],
      title: chapterMatch[3].trim(),
      courseOrder: chapters.length + 1,
      sections: [],
    }
    appendixSectionCount = 0
    continue
  }

  const appendixMatch = line.match(appendixPattern)
  if (appendixMatch) {
    finishChapter()
    chapter = {
      id: 'appendix',
      bookNumber: 'Appendix',
      title: appendixMatch[2].trim(),
      courseOrder: chapters.length + 1,
      sections: [],
    }
    appendixSectionCount = 0
    appendixBookNumber = appendixMatch[1]
    continue
  }

  const sectionMatch = line.match(sectionPattern)
  if (sectionMatch && chapter) {
    finishSection()
    section = {
      id: sectionMatch[1],
      number: sectionMatch[1],
      title: sectionMatch[2].trim(),
      lines: [],
    }
    continue
  }

  if (chapter?.id === 'appendix') {
    const appendixSectionMatch = line.match(appendixSectionPattern)
    if (appendixSectionMatch) {
      finishSection()
      appendixSectionCount += 1
      section = {
        id: `${appendixBookNumber}.${appendixSectionCount}`,
        number: `${appendixBookNumber}.${appendixSectionCount}`,
        title: appendixSectionMatch[1].trim(),
        lines: [],
      }
      continue
    }
  }

  if (section) section.lines.push(line)
}

finishChapter()

const totalSections = chapters.reduce((count, item) => count + item.sections.length, 0)
if (!chapters.length || totalSections < 50) {
  throw new Error(`Expected at least 50 sections, found ${totalSections}. Check the source headings.`)
}

const output = `// Generated by scripts/buildCcnaCourse.mjs from docs/CCNA_NETWORKING_KNOWLEDGE_BASE.md.\n// Run \`npm run content:ccna\` after editing the source. Do not edit by hand.\n\nexport interface GeneratedCcnaSection {\n  id: string\n  number: string\n  title: string\n  markdown: string\n}\n\nexport interface GeneratedCcnaChapter {\n  id: string\n  bookNumber: string\n  title: string\n  courseOrder: number\n  sections: GeneratedCcnaSection[]\n}\n\nexport const generatedCcnaChapters: GeneratedCcnaChapter[] = ${JSON.stringify(chapters, null, 2)}\n`

fs.writeFileSync(outputPath, output)
console.log(`Wrote ${totalSections} sections across ${chapters.length} chapters to ${path.relative(root, outputPath)}`)
for (const item of chapters) console.log(`  ${item.id}: ${item.sections.length} sections · ${item.title}`)
